// 3. Hotspots List
router.get("/hotspots", (req, res) => {
  const page = Math.max(1, parseInt(req.query.page, 10) || 1);
  const pageSize = Math.min(5000, Math.max(1, parseInt(req.query.page_size, 10) || 10));
  const maxPoints = req.query.max_points ? parseInt(req.query.max_points, 10) : 5000;

  const allFiltered = dataService.filterHotspots(req.query);
  const total = allFiltered.length;

  const startIndex = (page - 1) * pageSize;
  const pagedItems = allFiltered.slice(startIndex, startIndex + Math.min(pageSize, maxPoints));

  res.json({
    data: pagedItems,
    meta: {
      total,
      page,
      page_size: pageSize,
      truncated: total > maxPoints,
    },
  });
});

