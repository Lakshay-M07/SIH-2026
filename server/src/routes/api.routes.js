// 11. Create Report
router.post("/reports", (req, res) => {
  const id = `rep_${String(dataService.reports.length + 1).padStart(3, "0")}`;
  const now = new Date().toISOString();

  const newReport = {
    id,
    name: req.body?.name || `Thermal Surveillance Report — ${now.slice(0, 10)}`,
    status: "ready",
    created_at: now,
    summary: `Comprehensive FIRMS/Sentinel-2 thermal report generated from current filter criteria. Total evaluated records: ${dataService.hotspots.length}.`,
  };

  dataService.reports.unshift(newReport);

  res.status(201).json({
    data: newReport,
  });
});

// 12. Get Report
router.get("/reports/:id", (req, res) => {
  const report = dataService.reports.find((r) => r.id === req.params.id);
  if (!report) {
    return res.status(404).json({ error: "Report not found" });
  }
  res.json({
    data: report,
  });
});

// 13. Download Report PDF
router.get("/reports/:id/download", (req, res) => {
  const report = dataService.reports.find((r) => r.id === req.params.id);
  const pdfBuffer = generateMinimalPdf(
    report?.name || "Thermogrid Intelligence Report",
    report?.summary || "Automated geospatial anomaly overview."
  );

  res.setHeader("Content-Type", "application/pdf");
  res.setHeader("Content-Disposition", `attachment; filename="${req.params.id}.pdf"`);
  res.send(pdfBuffer);
});

// 14. Analyst Review
router.post("/analyst-review", (req, res) => {
  const { hotspot_id, classification, note, reviewer } = req.body;

  if (!hotspot_id || !classification || !reviewer) {
    return res.status(400).json({ error: "Missing required fields: hotspot_id, classification, reviewer" });
  }

  const verification = dataService.saveReview(hotspot_id, classification, reviewer, note || "Reviewed by analyst");
  if (!verification) {
    return res.status(404).json({ error: "Hotspot not found" });
  }

  res.json({
    data: verification,
  });
});

// 15. Live Ingestion Trigger & Status
router.post("/ingest/firms", async (_req, res) => {
  try {
    const result = await firmsIngestService.ingestLiveFirmsData();
    res.json({
      data: {
        status: "success",
        ingested_count: result.count,
        source: result.source,
        total_active_hotspots: dataService.hotspots.length,
        timestamp: new Date().toISOString(),
        next_scheduled: firmsIngestService.nextRun,
      },
    });
  } catch (err) {
    res.status(500).json({ error: err.message });
  }
});

router.get("/ingest/status", (_req, res) => {
  res.json({
    data: firmsIngestService.getStatus(),
  });
});

