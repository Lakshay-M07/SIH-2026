// Helper to generate minimal valid PDF buffer
function generateMinimalPdf(title, summary) {
  const safeTitle = (title || "Thermal Intelligence Report").replace(/[^\x20-\x7E]/g, "");
  const safeSummary = (summary || "Report generated by Thermogrid Intelligence Platform.").replace(/[^\x20-\x7E]/g, "");
  const stream = `BT /F1 18 Tf 50 740 Td (${safeTitle}) Tj ET\nBT /F1 11 Tf 50 700 Td (${safeSummary}) Tj ET`;
  const len = stream.length;

  const pdf = `%PDF-1.4
1 0 obj <</Type /Catalog /Pages 2 0 R>> endobj
2 0 obj <</Type /Pages /Kids [3 0 R] /Count 1>> endobj
3 0 obj <</Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Contents 4 0 R /Resources <</Font <</F1 5 0 R>>>>>> endobj
4 0 obj <</Length ${len}>>
stream
${stream}
endstream
endobj
5 0 obj <</Type /Font /Subtype /Type1 /BaseFont /Helvetica>> endobj
xref
0 6
0000000000 65535 f 
0000000010 00000 n 
0000000060 00000 n 
0000000117 00000 n 
0000000228 00000 n 
0000000${(290 + len).toString().padStart(3, "0")} 00000 n 
trailer <</Size 6 /Root 1 0 R>>
startxref
${360 + len}
%%EOF`;
  return Buffer.from(pdf, "utf-8");
}

